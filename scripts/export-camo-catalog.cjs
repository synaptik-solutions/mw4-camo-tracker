const fs = require('node:fs');
const { weapons, allCamosForWeapon } = require('../src/camoCatalog');
const data = Object.fromEntries(weapons.map(w => [w.name, allCamosForWeapon(w).map(c => c.name)]));
const content = '# Generated by scripts/export-camo-catalog.cjs; edit src/camoCatalog.js.\nCATALOG = '+JSON.stringify(data,null,2)+'\n';
const target = require('node:path').join(__dirname,'..','worker','camo_catalog.py');
const isCurrent = actual => actual.replace(/\r\n/g,'\n') === content;
if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (!isCurrent(fs.readFileSync(target,'utf8'))) throw new Error('Worker camo catalog is out of date');
  } else fs.writeFileSync(target,content);
}
module.exports={isCurrent,content};
